#!/usr/bin/env python3
"""Generate the cross-language source-policy contract without runtime tooling."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "protocol/source-policy.schema.json"
MODEL_PROFILE_SCHEMA = ROOT / "protocol/model-profile.schema.json"
# The Prettier hook formats generated TypeScript at frontend/prettier.config.js's
# default 80-column width. Emit that layout so the hook and --check agree.
PRETTIER_PRINT_WIDTH = 80
ENUM_VALUE = re.compile(r"[a-z][a-z0-9]*(?:_[a-z0-9]+)*")


def variant(value: str) -> str:
    return "".join(part.capitalize() for part in value.split("_"))


def serde_snake_case(name: str) -> str:
    """Apply serde's `rename_all = "snake_case"` rule to a Rust variant."""
    return "".join(
        ("_" if index and char.isupper() else "") + char.lower()
        for index, char in enumerate(name)
    )


def string_enum(values: object, label: str) -> list[str]:
    if (
        not isinstance(values, list)
        or not values
        or not all(isinstance(value, str) for value in values)
    ):
        raise ValueError(f"{label} enum must be a non-empty list of strings")
    if len(set(values)) != len(values):
        raise ValueError(f"{label} enum must contain unique IDs")
    for value in values:
        # Rust deserializes through the generated variant name, so a value it
        # cannot round-trip would be rejected only by the Rust runtime.
        if not ENUM_VALUE.fullmatch(value) or serde_snake_case(variant(value)) != value:
            raise ValueError(f"{label} value {value!r} must round-trip as snake_case")
    return values


def ts_const_array(name: str, values: list[str]) -> list[str]:
    items = [f"'{value}'" for value in values]
    line = f"export const {name} = [{', '.join(items)}] as const;"
    if len(line) <= PRETTIER_PRINT_WIDTH:
        return [line]
    return [
        f"export const {name} = [",
        *(f"  {item}," for item in items),
        "] as const;",
    ]


def render() -> dict[Path, str]:
    schema = json.loads(SCHEMA.read_text())
    try:
        ids = schema["$defs"]["SourcePolicyId"]["enum"]
    except (KeyError, TypeError) as exc:
        raise ValueError("SourcePolicyId must define an enum") from exc
    ids = string_enum(ids, "SourcePolicyId")
    ts = [
        "// Generated by scripts/generate_protocol_types.py; edit protocol/source-policy.schema.json.",
        *ts_const_array("SOURCE_POLICY_IDS", ids),
    ]
    ts += [
        "",
        "export type SourcePolicyId = (typeof SOURCE_POLICY_IDS)[number];",
        "",
        "export interface SourcePolicy {",
    ]
    py = [
        '"""Generated source-policy contract. Edit protocol/source-policy.schema.json."""',
        "",
        "from typing import Literal, TypedDict",
        "",
        "SourcePolicyId = Literal[",
    ]
    py += [f'    "{value}",' for value in ids]
    py += ["]", "", "SOURCE_POLICY_IDS: tuple[SourcePolicyId, ...] = ("]
    py += [f'    "{value}",' for value in ids]
    py += [")", "", "", "class SourcePolicy(TypedDict, total=False):"]
    types = {
        "boolean": ("boolean", "bool"),
        "integer": ("number", "int"),
        "string": ("string", "str"),
    }
    for name, definition in schema["properties"].items():
        if definition["type"] == "array":
            if definition.get("items") != {"$ref": "#/$defs/SourcePolicyId"}:
                raise ValueError(f"Unsupported array item schema for {name}")
            ts_type, py_type = "SourcePolicyId[]", "list[SourcePolicyId]"
        else:
            ts_type, py_type = types[definition["type"]]
        ts.append(f"  {name}?: {ts_type};")
        py.append(f"    {name}: {py_type}")
    ts.append("}")
    outputs = {
        ROOT / "frontend/types/sourcePolicy.ts": "\n".join(ts) + "\n",
        ROOT / "builder/nat_helpers/src/nat_helpers/source_policy_types.py": "\n".join(
            py
        )
        + "\n",
    }
    profiles = string_enum(
        json.loads(MODEL_PROFILE_SCHEMA.read_text()).get("enum"), "ModelProfile"
    )
    outputs[ROOT / "frontend/types/modelProfile.ts"] = "\n".join(
        [
            "// Generated by scripts/generate_protocol_types.py; edit protocol/model-profile.schema.json.",
            *ts_const_array("MODEL_PROFILES", profiles),
            "",
            "export type ModelProfile = (typeof MODEL_PROFILES)[number];",
            "",
        ]
    )
    outputs[ROOT / "builder/nat_helpers/src/nat_helpers/model_profile_types.py"] = (
        '"""Generated model-profile contract. Edit protocol/model-profile.schema.json."""\n\n'
        "from typing import Literal\n\nModelProfile = Literal[\n"
        + "".join(f'    "{value}",\n' for value in profiles)
        + "]\n\nMODEL_PROFILES: tuple[ModelProfile, ...] = (\n"
        + "".join(f'    "{value}",\n' for value in profiles)
        + ")\n"
    )

    rs = [
        "// Generated by scripts/generate_protocol_types.py; edit protocol/*.schema.json.",
        "#![allow(dead_code)]",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    for name, values in [("ModelProfile", profiles), ("SourcePolicyId", ids)]:
        rs += [
            "#[derive(Clone, Copy, Debug, Deserialize, Serialize, PartialEq, Eq)]",
            '#[serde(rename_all = "snake_case")]',
            f"pub enum {name} {{",
            *[f"    {variant(value)}," for value in values],
            "}",
            "",
        ]
    rs += [
        "#[derive(Clone, Debug, Default, Deserialize, Serialize)]",
        '#[serde(rename_all = "camelCase")]',
        "pub struct SourcePolicy {",
    ]
    rust_types = {
        "boolean": "bool",
        "integer": "i64",
        "string": "String",
        "array": "Vec<SourcePolicyId>",
    }
    for name, definition in schema["properties"].items():
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
        rs += [
            '    #[serde(skip_serializing_if = "Option::is_none")]',
            f"    pub {snake}: Option<{rust_types[definition['type']]}>,",
        ]
    rs += [
        "    #[serde(flatten)]",
        "    pub extra: std::collections::HashMap<String, serde_json::Value>,",
        "}",
    ]
    outputs[ROOT / "builder/runtime/src/protocol.rs"] = "\n".join(rs) + "\n"
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in render().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        print("Stale protocol types: " + ", ".join(stale))
        print("Run python3 scripts/generate_protocol_types.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
