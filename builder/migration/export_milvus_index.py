def generate_types(root, service, methods):
    """Generate Prost models directly from the consumer's pinned descriptors."""
    if (root / "tests/fixtures/milvus-search.json").exists():
        methods = sorted(set(methods) | {"Search"})
    descriptors = {}

    def visit(desc):
        if (
            desc.full_name in descriptors
            or desc.full_name == "milvus.proto.common.Status"
        ):
            return
        descriptors[desc.full_name] = desc
        for field in desc.fields:
            if field.message_type:
                if field.message_type.GetOptions().map_entry:
                    value = field.message_type.fields_by_name["value"]
                    if value.message_type:
                        visit(value.message_type)
                else:
                    visit(field.message_type)

    # Discover indexing messages first, then the production retrieval messages.
    for name in methods:
        if name == "Search":
            continue
        method = service.methods_by_name[name]
        visit(method.input_type)
        visit(method.output_type)
    # CreateCollection embeds its schema as bytes rather than a message field.
    visit(
        service.file.pool.FindMessageTypeByName("milvus.proto.schema.CollectionSchema")
    )
    if "Search" in methods:
        method = service.methods_by_name["Search"]
        visit(method.input_type)
        visit(method.output_type)
        # SearchRequest embeds dense vectors as an opaque PlaceholderGroup.
        visit(
            service.file.pool.FindMessageTypeByName(
                "milvus.proto.common.PlaceholderGroup"
            )
        )
    if len({d.name for d in descriptors.values()}) != len(descriptors):
        raise RuntimeError("Ambiguous protobuf type names")

    def snake(name):
        return re.sub(
            r"([a-z0-9])([A-Z])", r"\1_\2", re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
        ).lower()

    def identifier(name):
        value = snake(name)
        return (
            "r#" + value
            if value
            in {"type", "ref", "match", "self", "loop", "move", "async", "await"}
            else value
        )

    def scalar(field):
        if field.message_type:
            return field.message_type.name, "message"
        return {
            1: ("f64", "double"),
            2: ("f32", "float"),
            3: ("i64", "int64"),
            4: ("u64", "uint64"),
            5: ("i32", "int32"),
            6: ("u64", "fixed64"),
            7: ("u32", "fixed32"),
            8: ("bool", "bool"),
            9: ("String", "string"),
            12: ("Vec<u8>", 'bytes = "vec"'),
            13: ("u32", "uint32"),
            14: ("i32", "int32"),
            15: ("i32", "sfixed32"),
            16: ("i64", "sfixed64"),
            17: ("i32", "sint32"),
            18: ("i64", "sint64"),
        }[field.type]

    lines = [
        "//! Generated by export_milvus_index.py from the pinned SDK descriptors.",
        "// Preserve protobuf oneof field names in generated enum variants.",
        "#![allow(clippy::enum_variant_names)]",
        "use crate::milvus_proto::Status;",
    ]
    for desc in descriptors.values():
        # Production handshakes use the shared metadata transport's messages.
        # Keep these SDK definitions for the retained wire round-trip tests.
        if desc.name in {
            "ConnectRequest",
            "ConnectResponse",
            "ClientInfo",
            "ServerInfo",
        }:
            lines.append("#[cfg(test)]")
        lines += [
            "#[derive(Clone, PartialEq, prost::Message)]",
            f"pub struct {desc.name} {{",
        ]
        for field in desc.fields:
            if field.containing_oneof:
                continue
            rust, wire = scalar(field)
            qualifier = ""
            if field.message_type and field.message_type.GetOptions().map_entry:
                key, key_wire = scalar(field.message_type.fields_by_name["key"])
                value, value_wire = scalar(field.message_type.fields_by_name["value"])
                rust = f"std::collections::HashMap<{key}, {value}>"
                wire = f'map = "{key_wire}, {value_wire}"'
            elif field.is_repeated:
                rust, qualifier = f"Vec<{rust}>", ", repeated"
            elif field.message_type:
                rust, qualifier = f"Option<{rust}>", ", optional"
            lines += [
                f'    #[prost({wire}{qualifier}, tag = "{field.number}")]',
                f"    pub {identifier(field.name)}: {rust},",
            ]
        for oneof in desc.oneofs:
            enum = "".join(p.capitalize() for p in oneof.name.split("_"))
            name = f"{snake(desc.name)}::{enum}"
            tags = ", ".join(str(field.number) for field in oneof.fields)
            lines += [
                f'    #[prost(oneof = "{name}", tags = "{tags}")]',
                f"    pub {identifier(oneof.name)}: Option<{name}>,",
            ]
        lines += ["}"]
        if desc.oneofs:
            lines += [f"pub mod {snake(desc.name)} {{"]
            for oneof in desc.oneofs:
                enum = "".join(p.capitalize() for p in oneof.name.split("_"))
                lines += [
                    "    #[derive(Clone, PartialEq, prost::Oneof)]",
                    f"    pub enum {enum} {{",
                ]
                for field in oneof.fields:
                    rust, wire = scalar(field)
                    if field.message_type:
                        rust = "super::" + rust
                    variant = "".join(
                        p.capitalize() for p in snake(field.name).split("_")
                    )
                    lines += [
                        f'        #[prost({wire}, tag = "{field.number}")]',
                        f"        {variant}({rust}),",
                    ]
                lines += ["    }"]
            lines += ["}"]
    lines += [
        "#[cfg(test)]",
        "pub fn reencode(method: &str, response: bool, bytes: &[u8]) -> Vec<u8> {",
        "    use prost::Message;",
        "    match (method, response) {",
    ]
    for name in methods:
        method = service.methods_by_name[name]
        for response, desc in [(False, method.input_type), (True, method.output_type)]:
            lines += [
                f'        ("{name}", {str(response).lower()}) => {desc.name}::decode(bytes).unwrap().encode_to_vec(),'
            ]
    lines += ['        _ => panic!("Uncaptured Milvus RPC"),', "    }", "}"]
    (root / "src/milvus_index_proto.rs").write_text("\n".join(lines) + "\n")


def export(root):
    import document_ingest_api as api
    import grpc
    import nat_nv_ingest.nat_nv_ingest as document
    from google.protobuf.json_format import MessageToDict, ParseDict
    from google.protobuf.message_factory import GetMessageClass
    from nv_ingest_client.util.vdb import milvus as sdk
