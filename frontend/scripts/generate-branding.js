#!/usr/bin/env node
// Generate one content-based URL map for React, the manifest, and the worker.
const { createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const BLOCK_START = '// BEGIN GENERATED BRANDING';
const BLOCK_END = '// END GENERATED BRANDING';

function hash(content) {
  return createHash('sha256').update(content).digest('hex').slice(0, 16);
}

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function generateBranding(root = path.join(__dirname, '..')) {
  const publicDir = path.join(root, 'public');
  const files = [
    '/favicon.png',
    ...fs
      .readdirSync(path.join(publicDir, 'icons'))
      .filter((file) => file.endsWith('.png'))
      .sort()
      .map((file) => `/icons/${file}`),
  ];
  const assets = Object.fromEntries(
    files.map((file) => [
      file,
      `${file}?v=${hash(fs.readFileSync(path.join(publicDir, file)))}`,
    ]),
  );

  const manifestFile = path.join(publicDir, 'manifest.json');
  const manifest = JSON.parse(
    fs.readFileSync(manifestFile, 'utf8'),
    (key, value) => {
      if (key !== 'src' || typeof value !== 'string') return value;
      const file = value.split('?')[0];
      if (file.startsWith('/icons/') && !assets[file]) {
        throw new Error(`Manifest references missing branding asset: ${file}`);
      }
      return assets[file] || value;
    },
  );
  const urls = {
    assets,
    // Hash the parsed manifest so formatting alone does not change its URL.
    manifest: `/manifest.json?v=${hash(JSON.stringify(manifest))}`,
  };
  const branding = { ...urls, version: hash(JSON.stringify(urls)) };

  // Keep human-authored manifest formatting and metadata intact.
  const versionedManifest = fs
    .readFileSync(manifestFile, 'utf8')
    .replace(/"src"\s*:\s*"([^"?]+)(?:\?[^"\s]*)?"/g, (match, file) =>
      assets[file]
        ? match.replace(/"[^"\s]+"$/, JSON.stringify(assets[file]))
        : match,
    );
  writeIfChanged(manifestFile, versionedManifest);
  writeIfChanged(
    path.join(root, 'generated', 'branding.ts'),
    `// Generated by scripts/generate-branding.js; do not edit.\n// prettier-ignore\nexport const branding = ${JSON.stringify(
      branding,
      null,
      2,
    )} as const;\n`,
  );

  const offlineFile = path.join(publicDir, 'offline.html');
  writeIfChanged(
    offlineFile,
    fs
      .readFileSync(offlineFile, 'utf8')
      .replace(/src="([^"?]+)(?:\?[^"\s]*)?"/g, (match, file) =>
        assets[file] ? `src="${assets[file]}"` : match,
      ),
  );

  const swFile = path.join(publicDir, 'sw.js');
  const worker = fs.readFileSync(swFile, 'utf8');
  if (!worker.includes(BLOCK_START) || !worker.includes(BLOCK_END)) {
    throw new Error('Service worker is missing generated branding markers');
  }
  writeIfChanged(
    swFile,
    worker.replace(
      new RegExp(`${BLOCK_START}[\\s\\S]*?${BLOCK_END}`),
      `${BLOCK_START} (scripts/generate-branding.js; do not edit)\n// prettier-ignore\nconst BRANDING = ${JSON.stringify(
        branding,
        null,
        2,
      )};\n${BLOCK_END}`,
    ),
  );
  return branding;
}

module.exports = { generateBranding };
if (require.main === module) generateBranding();
